"""TTS에 넘기기 직전 텍스트에만 적용하는 발음 보정.

`infer.py`가 torch/qwen_tts를 모듈 최상단에서 import해서(GPU 없는 빠른 pytest 스위트가
못 돌게 됨), 순수 문자열 치환 로직만 별도 모듈로 뺐다.

"닭을"(ㄺ 겹받침 연음)이 이 체크포인트에서 "달근"/"딸을" 등으로 잘못 발음되는 걸 실측
확인(2026-08-19) — "달글"로 표기해서 넘기면 정상 발음됨(직접 청취 확인).
문장 전체를 g2pk/g2pk3(한국어 G2P 라이브러리)로 돌려서 일반화하는 것도 시도했으나,
"소금을 넣고"->"소그믈 러코"처럼 "~을/를 넣고" 같은 흔한 조리 표현에서 단어 경계를
잘못 넘나드는 버그가 두 라이브러리 모두에 있어(2026-08-19 실측, docs/decisions.md 참고)
채택하지 않았다. 대신 실제로 문제 확인된 단어만 정규식으로 직접 치환한다 — 문장의 나머지
부분은 안 건드리므로 G2P 라이브러리의 교차-단어 버그에 노출되지 않는다. 새 단어에서 같은
문제가 발견되면 이 딕셔너리에 추가하면 된다.
"""

from __future__ import annotations

import re

PRONUNCIATION_FIXES: dict[str, str] = {
    "닭을": "달글",
}

_PATTERN = re.compile("|".join(re.escape(k) for k in PRONUNCIATION_FIXES))

# 2026-09-04 — "2. 스팸을 깍둑썰기 해주세요..."에서 맨 앞의 "2."가 숫자 "둘/이"로
# 안 읽히고 "두"/"뚜"처럼 뭉개져 들린다는 리포트. 조리 단계 텍스트는 등록 시 전부
# f"{i}. {text}" 형식으로 저장돼서(registration.py 등) "N. "이 항상 맨 앞에 붙는다
# — 숫자+마침표 조합을 모델이 애매하게 처리하는 것으로 보인다(끝음절 문제와 마찬가지로
# Qwen3-TTS의 숫자/약어 처리 한계로 추정, 1.5 원칙 — 확정 인과관계는 미검증). 숫자를
# 남겨두고 어떻게든 잘 읽히길 바라는 대신, 아예 한글 단계 표현("이단계, ")으로 완전히
# 바꿔서 넘긴다 — 숫자 자체가 사라지므로 이 모호함이 원천적으로 없어진다. 조리 단계가
# 20개를 넘는 레시피는 실측상 없었음(500개 표준 레시피 기준) — 그보다 크면 안전하게
# 원문 숫자를 그대로 둔다(1.5 원칙, 지어내지 않음).
_STEP_NUMBER_WORDS: dict[int, str] = {
    1: "일", 2: "이", 3: "삼", 4: "사", 5: "오",
    6: "육", 7: "칠", 8: "팔", 9: "구", 10: "십",
    11: "십일", 12: "십이", 13: "십삼", 14: "십사", 15: "십오",
    16: "십육", 17: "십칠", 18: "십팔", 19: "십구", 20: "이십",
}
_STEP_PREFIX_PATTERN = re.compile(r"^\s*(\d{1,2})\.\s*")


def _replace_step_prefix(match: re.Match[str]) -> str:
    word = _STEP_NUMBER_WORDS.get(int(match.group(1)))
    if word is None:
        return match.group(0)  # 매핑 밖 숫자(21+) — 안전하게 원문 그대로 둔다
    return f"{word}단계, "


# 2026-09-03 — "문장 끝 음절(주로 '~요')이 작게/흐리게 발음돼 안 들린다"는 반복 리포트
# 대응. 재생 쪽은 이미 브라우저 <audio> 이벤트(play/pause/ended)를 직접 찍어서 끝까지
# 완주함을 확인했고(화면 잔상 청소 레이스도 배제, ui/theme.py의 tail_ms 패딩 관련
# 문서 참고), 원본 wav 파일 진폭도 문장 끝 50~100ms 구간이 다른 음절보다 확연히 작았다
# (재생 버그가 아니라 생성 쪽 발음 문제로 확인) — 즉 "재생이 잘려서"가 아니라 "모델이
# 원래 작게/짧게 발음해서" 안 들리는 것. DB의 조리 단계 텍스트는 대부분 마침표 없이
# 끝난다(예: "...써는 방법이에요") — 종결 부호가 없으면 모델이 "문장이 아직 안
# 끝났다"고 보고 마지막 음절을 확정 짓지 않는 것으로 추정된다(1.5 원칙 — 확정 인과
# 관계는 미검증, 청취 보고 기반의 시도). 이미 마침표/물음표/느낌표로 끝나는 문장은
# 그대로 두고, 없는 경우에만 마침표를 붙여 문장 종결을 명시적으로 준다. 재발하면(또는
# 효과 없으면) 이 로직부터 되돌아볼 것.
#
# 같은 날 추가 — 마침표 뒤에 공백 1개를 무조건 더 붙인다(팀 요청). "이 토크나이저가
# 끝에 붙는 공백을 어떻게 처리하는지"는 이 저장소에서 검증 못 했다(위 파일 docstring과
# 같은 이유 — 실제 생성 경로의 내부 토크나이저를 확인할 GPU 환경이 로컬에 없음). 마침표
# 만으로 부족하면 공백이 "문장이 진짜 끝났다"는 신호를 하나 더 얹어줄 수 있다는 추정에
# 따른 추가 시도 — 이것도 효과 검증 전이니, 재발하면 이 줄부터 되돌아볼 것.
#
# 2026-09-04 실제 청취 검증 결과 — 위 마침표+공백은 "어느 정도 효과는 있지만 완전히
# 고쳐지진 않음"으로 확인됨. 같은 날 tts/infer.py에 오디오 레벨 무음 판정+재시도를
# 추가해서 "아예 안 들리는" 케이스는 해결됐고(실측: seed 0~7 중 5/8이 무음이었던 문장이
# 재시도로 정상화됨), 이제 남은 건 "들리긴 하는데 끝이 좀 급하게/짧게 끝나는 느낌"이라는
# 팀 피드백 — 마침표 하나로는 부족했다는 뜻으로 보고, 한때 종결 신호를 마침표+느낌표
# (".!")로 더 세게 줬었다.
#
# 이 증상이 Qwen3-TTS 자체의 알려진 미해결 이슈라는 것도 같은 날 확인했다
# (github.com/QwenLM/Qwen3-TTS/discussions/161 — "Last syllable being cut in
# isolated words"). 그 스레드의 리포터도 temperature 조정/마침표/말줄임표를 다
# 시도했지만 안 됐다고 직접 밝혔고(우리와 같은 패턴), 유일하게 나온 커뮤니티 우회법이
# "마침표 뒤에 진짜 안 읽히는 더미 기호를 붙이는 것"이다(원문 예시: 러시아어 문장
# 끝에 " ^." 추가 — 그 기호 자체는 안 읽히고 그 앞 단어가 제대로 발음됐다는 후기,
# 메인테이너 확인은 아님). 이 더미 기호(^)를 추가하고 실제 청취 검증 결과 끝음절이
# 확실히 다 들리는 것으로 확인됨(2026-09-04, 팀 확인) — 마침표+느낌표(".!")와
# 앞 공백은 실제로는 불필요했던 것으로 보여 걷어내고, 최소한으로 "." + "^"만 남긴다
# (예: "...방법이에요" -> "...방법이에요.^"). "^"는 조리 텍스트에 등장할 일이 없는
# 기호라 실수로 다른 단어와 헷갈릴 걱정도 없다.
#
# 2026-09-07 — "^"가 "안 읽힌다"는 전제가 이 모델/한국어 조합에서는 보장이 아니라는
# 게 확인됐다. RunPod 운영 캐시 파일(예: 조리 4단계 "...함께 익혀주세요")을 직접
# 파형 분석한 결과, 정상 발화가 끝나고(약 6.66s) 0.3초가량 무음이 지나간 뒤 "^"
# 자리에서 **실제 대사 피크(0.15)보다 4배 이상 큰(피크 0.65) 소리가 0.15~0.2초간
# 터졌다가 뚝 끊기는** 패턴이 재현됐다(같은 레시피의 다른 스텝에서도 재현 — seed에
# 따라 매번은 아님). 게다가 이 버스트는 `infer.py`의 `_tail_silence_ratio()`(끝
# 150ms RMS 판정)를 오히려 통과시킨다 — 그 150ms 구간 안에 버스트의 큰 피크가 걸리면
# "안 무음"으로 판정되어 재시도가 아예 발동하지 않기 때문이다.
#
# 한 번은 "^" 부착 자체를 그만두는 쪽으로 갔었으나(부작용이 더 눈에 띈다는 판단),
# "^"가 끝음절 흐림 문제에 실제로 효과가 있었던 것도 2026-09-04에 이미 확인된
# 사실이라 되돌렸다 — "^"는 그대로 유지하고, 대신 `infer.py`에 파형 레벨 트리밍
# (`_trim_trailing_artifact()`)을 추가해서 "무음 뒤 튀는 소리" 패턴 자체를 감지해
# 잘라내는 쪽으로 방향을 정했다. 즉 "^"가 주는 이득(끝음절 확정)은 그대로 받고,
# 그게 가끔 만드는 부작용(튀는 소리)만 후처리로 제거하는 구조.
_DUMMY_TAIL_SUFFIX = "^"

_SENTENCE_END_CHARS = (".", "!", "?", "…")


def apply_pronunciation_fixes(text: str) -> str:
    """TTS에 넘기기 직전에만 적용 — 화면 표시·로그·DB에 쓰이는 원문은 건드리지 않는다."""

    text = _STEP_PREFIX_PATTERN.sub(_replace_step_prefix, text, count=1)

    if PRONUNCIATION_FIXES:
        text = _PATTERN.sub(lambda m: PRONUNCIATION_FIXES[m.group(0)], text)

    stripped = text.rstrip()
    if not stripped:
        return text

    if not stripped.endswith(_SENTENCE_END_CHARS):
        stripped += "."

    stripped += _DUMMY_TAIL_SUFFIX

    return stripped + " "
